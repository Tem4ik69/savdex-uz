-- Маркетплейс: роль сайта (savdex_django) больше не удаляет продавцов,
-- товары и их варианты.
--
-- Сайт и админка эти строки не удаляют никогда: заявка продавца меняет
-- статус, товар снимается с продажи, убранный продавцом вариант
-- выключается и помечается (_removed) — строки нужны для журнала и
-- будущих заказов. А удаление товара или варианта каскадом стёрло бы фото,
-- характеристики, избранное и корзины покупателей. Права на DELETE,
-- выданные миграцией 2026_11_19_100000 вместе с остальными, лишние:
-- ошибка в коде или уязвимость не должны суметь стереть каталог.
--
-- Каскадов в эти таблицы нет (компания и категория — on delete restrict,
-- пользователь — set null, а его выполняет база от имени владельца).
-- Остальные таблицы маркетплейса (фото, характеристики, избранное,
-- корзина) сайт удаляет штатно — права на них не тронуты.

do $$ begin
    if exists (select from pg_roles where rolname = 'savdex_django') then
        revoke delete on market_sellers, market_products, market_product_variants
        from savdex_django;
    end if;
end $$;
